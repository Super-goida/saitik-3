// Функция загрузки миссии (БЕЗ ЭКРАНИРОВАНИЯ HTML для секретных слов)
function loadMission(missionId) {
    const mission = missionsData[missionId];
    if (!mission) return;

    // Для миссий с секретными словами НЕ экранируем HTML
    const isSecretMission = (missionId === "УЛУЧШЕНИЕ СВЯЗИ" || missionId === "ДАННЫЕ СТАРОГО МИРА");
    
    // Блок 1: Название миссии + Обзор
    const overviewSection = document.getElementById('missionOverview');
    if (overviewSection) {
        overviewSection.innerHTML = `
            <div class="mission-title">${escapeHtml(mission.title)}</div>
            <div class="section-header">ОБЗОР МИССИИ</div>
            <div class="section-text">${isSecretMission ? mission.overview : escapeHtml(mission.overview)}</div>
        `;
    }

    // Блок 2: Ход выполнения
    const progressSection = document.getElementById('missionProgress');
    if (progressSection) {
        progressSection.innerHTML = `
            <div class="section-header">ХОД ВЫПОЛНЕНИЯ</div>
            <div class="section-text">${isSecretMission ? mission.progress : escapeHtml(mission.progress)}</div>
        `;
    }

    // Блок 3: Операционная эффективность и Стратегическое значение
    const footerSection = document.getElementById('missionFooter');
    if (footerSection) {
        footerSection.innerHTML = `
            <div class="section-header">ОПЕРАЦИОННАЯ ЭФФЕКТИВНОСТЬ</div>
            <div class="section-text">${isSecretMission ? mission.efficiency : escapeHtml(mission.efficiency)}</div>
            <div class="section-header" style="margin-top: 15px;">СТРАТЕГИЧЕСКОЕ ЗНАЧЕНИЕ</div>
            <div class="section-text">${isSecretMission ? mission.value : escapeHtml(mission.value)}</div>
        `;
    }
}

// Защита от XSS (только для обычного текста)
function escapeHtml(str) {
    return str.replace(/[&<>]/g, function(m) {
        if (m === '&') return '&amp;';
        if (m === '<') return '&lt;';
        if (m === '>') return '&gt;';
        return m;
    });
}

// Получение параметров из URL
function getMissionFromUrl() {
    const urlParams = new URLSearchParams(window.location.search);
    return urlParams.get('mission');
}

// Загрузка при открытии страницы
document.addEventListener('DOMContentLoaded', () => {
    const missionName = getMissionFromUrl();
    if (missionName && missionsData[missionName]) {
        loadMission(missionName);
    } else {
        loadMission("УЛУЧШЕНИЕ СВЯЗИ");
    }
});